#[test]
fn lockfile_noise_is_summarised_not_dumped() {
    let repo = seeded_repo();
    repo.write(
        "Cargo.lock",
        "# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = \"serde\"\nversion = \"1.0.229\"\n",
    );
    repo.git(&["add", "-A"]);

    let output = repo.wyckoff(&["-p", "mock", "--dry-run"]);
    let text = stdout(&output);
    assert!(
        text.contains("added Cargo.lock (+6 -0)") || text.contains("modified Cargo.lock"),
        "the lockfile should be a one-liner: {text}"
    );
    assert!(
        !text.contains("automatically @generated by Cargo"),
        "lockfile bodies must not be sent: {text}"
    );
    assert!(
        !text.contains("[[package]]"),
        "lockfile bodies must not be sent: {text}"
    );
}
